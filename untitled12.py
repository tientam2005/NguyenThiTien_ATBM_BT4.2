import math

# Thong tin sinh vien
stt = 14
ho_ten = "NGUYENTHITIEN"

# Buoc 1: Chon p, q
p = 19
q = 31

# Buoc 2: Tinh n va phi
n = p * q
phi = (p - 1) * (q - 1)

# Buoc 3: Tim e la so nguyen to nho nhat
def la_so_nguyen_to(x):
    if x < 2:
        return False
    for i in range(2, math.isqrt(x) + 1):
        if x % i == 0:
            return False
    return True

for i in range(2, phi):
    if la_so_nguyen_to(i) and math.gcd(i, phi) == 1:
        e = i
        break

# Buoc 4: Tim khoa bi mat d
d = pow(e, -1, phi)

print("STT:", stt)
print("Ho ten:", ho_ten)
print("n =", n)
print("phi =", phi)
print("e =", e)
print("d =", d)
print("Khoa cong khai:", (e, n))
print("Khoa bi mat:", (d, n))

# Buoc 5: Ma hoa tung chu cai
ban_ma = []

print("\nBANG MA HOA RSA")
print("Ky tu | ASCII | Ma hoa")

for ky_tu in ho_ten:
    M = ord(ky_tu)
    C = pow(M, e, n)
    ban_ma.append(C)
    print(f"{ky_tu:^6} | {M:^5} | {C:^6}")

print("\nBan ma:", ban_ma)

# Buoc 6: Giai ma de kiem tra
giai_ma = ""

for C in ban_ma:
    M = pow(C, d, n)
    giai_ma += chr(M)

print("Giai ma:", giai_ma)